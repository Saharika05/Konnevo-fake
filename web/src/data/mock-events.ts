import type { EventItem, EventMode, EventType } from "@/lib/api/types";

function event(
  id: string,
  title: string,
  type: EventType,
  mode: EventMode,
  startDate: string,
  endDate: string | undefined,
  place: string,
  clubName: string,
  interestedCount: number,
  description: string,
  expired = false,
): EventItem {
  return {
    id,
    title,
    type,
    mode,
    startDate,
    endDate,
    place,
    registrationUrl: `https://example.com/${id}`,
    description,
    clubName,
    interestedCount,
    expired,
  };
}

